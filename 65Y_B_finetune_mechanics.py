#!/usr/bin/env python3
"""65Y-B: controlled mechanics-head-only fine-tuning of existing V4 ensembles.

Runs on Mac M1 Max (MPS if available). Uses existing 64J train/validation splits.
Training uses original data/hybrid_bulk_7region only, NEVER the 65W reference.
Displacement and interface-force heads remain byte-for-byte unchanged.
No approximate physics constraints are introduced until 65Y-A has been validated.

Quick check:
  python3 65Y_B_finetune_mechanics.py --project . --check-only
Training:
  python3 65Y_B_finetune_mechanics.py --project . --members 5 --epochs 150

Output existing protection: manually delete ONLY
 results/65Y_middle_mechanics/B_mechanics_finetune before rerun.
"""
import argparse, copy, hashlib, json, random, sys
from pathlib import Path
import numpy as np
import pandas as pd
import torch
from torch.utils.data import DataLoader, TensorDataset

SEGMENTS=('inner_left','inner_right')
COMPS=('11','22','33','12','13','23')
FIELD_WEIGHTS=np.array([1.,2.5,1.,2.,1.,1.],dtype=np.float32)


def read_checkpoint(path):
    # Only load trusted checkpoints generated by user's own repository code.
    x=torch.load(path,map_location='cpu',weights_only=False)
    required=['model_state_dict','branch_dim','number_force_coefficients',
              'branch_mean','branch_std','coordinate_min','coordinate_max','LE_mean','LE_std','S_mean','S_std']
    missing=[k for k in required if k not in x]
    if missing:raise RuntimeError('%s missing checkpoint keys: %s'%(path,missing))
    return x


def dataset_for(root,segment):
    d=root/'data'/'hybrid_bulk_7region'/segment
    for fn in ('branch_inputs.npy','ip_coordinates.npy','LE.npy','S.npy','split_assignment.csv'):
        if not (d/fn).is_file():raise FileNotFoundError(str(d/fn))
    X=np.load(d/'branch_inputs.npy',allow_pickle=False).astype(np.float32)
    ip=np.load(d/'ip_coordinates.npy',allow_pickle=False).astype(np.float32)
    LE=np.load(d/'LE.npy',allow_pickle=False).astype(np.float32)
    S=np.load(d/'S.npy',allow_pickle=False).astype(np.float32)
    split=pd.read_csv(d/'split_assignment.csv')
    if not {'Index','Split'}.issubset(split.columns):raise RuntimeError('Unexpected split_assignment columns')
    if X.ndim!=2 or ip.ndim!=2 or ip.shape[1]!=3 or LE.shape!=(len(X),len(ip),6) or S.shape!=LE.shape:
        raise RuntimeError(segment+' unexpected model input/target shapes')
    if not all(np.isfinite(v).all() for v in (X,ip,LE,S)):
        raise RuntimeError(segment+' nonfinite training inputs')
    inds={s:split.loc[split['Split']==s,'Index'].to_numpy(dtype=int) for s in ('train','validation','test')}
    if any(len(v)<1 for v in inds.values()):raise RuntimeError(segment+' missing train/validation/test split')
    concat=np.concatenate(list(inds.values()))
    if sorted(concat.tolist())!=list(range(len(X))):raise RuntimeError(segment+' splits overlap or omit examples')
    return X,ip,LE,S,inds


def prepare(root,seg,ck):
    X,ip,LE,S,inds=dataset_for(root,seg)
    def ar(k):return np.asarray(ck[k],dtype=np.float32)
    bmu,bstd=ar('branch_mean'),ar('branch_std')
    lemu,lestd=ar('LE_mean'),ar('LE_std')
    smu,sstd=ar('S_mean'),ar('S_std')
    cmin,cmax=ar('coordinate_min'),ar('coordinate_max')
    if len(bmu)!=X.shape[1] or len(bstd)!=X.shape[1] or len(lemu)!=6 or len(lestd)!=6 or len(smu)!=6 or len(sstd)!=6:
        raise RuntimeError('Checkpoint normalization incompatible with dataset for '+seg)
    if len(cmin)!=3 or len(cmax)!=3 or np.any(bstd<=0) or np.any(lestd<=0) or np.any(sstd<=0):
        raise RuntimeError('Invalid checkpoint normalization statistics')
    if not np.allclose(X[inds['train']].mean(axis=0),bmu,rtol=5e-4,atol=2e-3):
        raise RuntimeError('Checkpoint branch normalization does not correspond to current training split')
    branch=(X-bmu)/bstd
    ipn=2*(ip-cmin)/np.maximum(cmax-cmin,1e-8)-1
    if np.max(np.abs(ipn))>1.001:raise RuntimeError('IP coordinate normalization outside trained range')
    data={'branch':torch.tensor(branch,dtype=torch.float32),
          'ip':torch.tensor(ipn,dtype=torch.float32),
          'LE':torch.tensor((LE-lemu)/lestd,dtype=torch.float32),
          'S':torch.tensor((S-smu)/sstd,dtype=torch.float32),
          'inds':inds, 'LE_mu':lemu,'LE_std':lestd,'S_mu':smu,'S_std':sstd}
    return data


def make_model(ck,device):
    from src.hybrid_bulk_operator_v4_7region import HybridBulkOperatorV4SevenRegion
    model=HybridBulkOperatorV4SevenRegion(
        branch_dim=int(ck['branch_dim']),
        number_force_coefficients=int(ck['number_force_coefficients']),
        hidden_dim=int(ck.get('hidden_dim',128)),latent_dim=int(ck.get('latent_dim',128)),
        depth=int(ck.get('depth',4)))
    model.load_state_dict(ck['model_state_dict'],strict=True)
    model=model.to(device)
    for p in model.parameters():p.requires_grad_(False)
    for p in list(model.strain_operator.parameters())+list(model.stress_operator.parameters()):
        p.requires_grad_(True)
    return model


def losses(model,b,LE,S,ip,baseLE,baseS,weights,anchor_weight):
    ple=model.strain_operator(b,ip)
    ps=model.stress_operator(b,ip)
    w=weights.reshape(1,1,6)
    fitted=((ple-LE).square()*w).mean()+((ps-S).square()*w).mean()
    anchor=(ple-baseLE).square().mean()+(ps-baseS).square().mean()
    return fitted+anchor_weight*anchor,fitted,ple,ps


def evaluate(model,data,indices,device,weights,batch_size=8):
    model.eval();total=0.;num=0
    ips=data['ip'].to(device);wt=weights.to(device)
    with torch.no_grad():
        for start in range(0,len(indices),batch_size):
            idx=indices[start:start+batch_size]
            b=data['branch'][idx].to(device)
            le=data['LE'][idx].to(device);s=data['S'][idx].to(device)
            p=model.strain_operator(b,ips);q=model.stress_operator(b,ips)
            score=((p-le).square()*wt).mean()+((q-s).square()*wt).mean()
            total+=float(score.item())*len(idx);num+=len(idx)
    return total/max(1,num)


def sha(path):
    h=hashlib.sha256()
    with open(path,'rb') as f:
        for part in iter(lambda:f.read(1024*1024),b''):h.update(part)
    return h.hexdigest()


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--project',default='.')
    ap.add_argument('--segments',nargs='+',default=list(SEGMENTS),choices=SEGMENTS)
    ap.add_argument('--members',type=int,default=5)
    ap.add_argument('--epochs',type=int,default=150)
    ap.add_argument('--patience',type=int,default=35)
    ap.add_argument('--batch-size',type=int,default=4)
    ap.add_argument('--lr',type=float,default=1.0e-5)
    ap.add_argument('--anchor',type=float,default=0.05)
    ap.add_argument('--device',choices=['auto','cpu','mps'],default='auto')
    ap.add_argument('--check-only',action='store_true')
    args=ap.parse_args()
    if not(1<=args.members<=5 and args.epochs>=1 and args.patience>=1 and args.batch_size>=1 and 0<args.lr<=1e-3 and args.anchor>=0):
        raise ValueError('Invalid training arguments')
    root=Path(args.project).expanduser().resolve()
    if str(root) not in sys.path:sys.path.insert(0,str(root))
    audit=root/'results'/'65Y_middle_mechanics'/'A_reference_physics_audit'/'65Y_A_summary.json'
    if not audit.is_file():raise FileNotFoundError('Run Step 65Y-A before training: '+str(audit))
    device=torch.device('mps' if args.device=='auto' and torch.backends.mps.is_available() else ('cpu' if args.device=='auto' else args.device))
    base=root/'results'/'v4_7region_direct'
    plans=[]
    for seg in args.segments:
        for m in range(1,args.members+1):
            path=base/seg/('member_%02d'%m)/'best_v4_7region.pt'
            if not path.is_file():raise FileNotFoundError('Missing original V4 checkpoint: '+str(path))
            plans.append((seg,m,path))
        dataset_for(root,seg)
    if args.check_only:
        print('65Y-B CHECK PASS: reference audit, original training splits, and',len(plans),'trusted V4 checkpoints found')
        print('Device:',device,' training only mechanics heads, no changes to interface/displacement')
        return
    out=root/'results'/'65Y_middle_mechanics'/'B_mechanics_finetune'
    if out.exists() and any(out.iterdir()):
        raise RuntimeError('Existing training output protected. Manually delete ONLY this folder before a fresh run:\n'+str(out))
    out.mkdir(parents=True,exist_ok=True)
    torch.set_num_threads(min(4,torch.get_num_threads()))
    weights=torch.tensor(FIELD_WEIGHTS,dtype=torch.float32,device=device)
    results=[]
    for seg,m,checkpoint_file in plans:
        seed=6500+100*SEGMENTS.index(seg)+m
        np.random.seed(seed);random.seed(seed);torch.manual_seed(seed)
        ck=read_checkpoint(checkpoint_file)
        data=prepare(root,seg,ck)
        indices=data['inds'];model=make_model(ck,device)
        initial_state={k:v.detach().cpu().clone() for k,v in model.state_dict().items()}
        original_model=copy.deepcopy(model).eval()
        for p in original_model.parameters():p.requires_grad_(False)
        trainset=TensorDataset(data['branch'][indices['train']],data['LE'][indices['train']],data['S'][indices['train']])
        loader=DataLoader(trainset,batch_size=args.batch_size,shuffle=True,drop_last=False)
        optimizer=torch.optim.Adam(list(model.strain_operator.parameters())+list(model.stress_operator.parameters()),
                                   lr=args.lr,weight_decay=1e-6)
        ip=data['ip'].to(device)
        baseline_val=evaluate(model,data,indices['validation'],device,weights)
        best_val=baseline_val;best_state=copy.deepcopy(initial_state);best_epoch=0;stale=0
        history=[]
        print('65Y-B %s member %d baseline val %.7f'%(seg,m,baseline_val),flush=True)
        for epoch in range(1,args.epochs+1):
            model.train()
            total=0.;count=0
            for b,le,s in loader:
                b=b.to(device);le=le.to(device);s=s.to(device)
                with torch.no_grad():
                    oldle=original_model.strain_operator(b,ip)
                    olds=original_model.stress_operator(b,ip)
                optimizer.zero_grad(set_to_none=True)
                loss,fit,_,_=losses(model,b,le,s,ip,oldle,olds,weights,args.anchor)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(list(model.strain_operator.parameters())+list(model.stress_operator.parameters()),1.0)
                optimizer.step()
                total+=float(loss.item())*len(b);count+=len(b)
            val=evaluate(model,data,indices['validation'],device,weights)
            history.append({'epoch':epoch,'train_loss':total/max(count,1),'validation_supervised_loss':val})
            if val<best_val-1e-8:
                best_val=val;best_epoch=epoch
                best_state={k:v.detach().cpu().clone() for k,v in model.state_dict().items()}
                stale=0
            else:stale+=1
            if epoch==1 or epoch%25==0:
                print('  epoch %3d train %.7f val %.7f best %.7f'%(epoch,total/max(count,1),val,best_val),flush=True)
            if stale>=args.patience:break
        # Compare frozen weights to original and save ONLY in results/65Y...
        frozen_prefixes=('displacement_operator.','force_coefficient_head.')
        for key in initial_state:
            if key.startswith(frozen_prefixes) and not torch.equal(initial_state[key],best_state[key]):
                raise RuntimeError('CRITICAL: modified frozen displacement or force parameter '+key)
        member_dir=out/seg/('member_%02d'%m)
        member_dir.mkdir(parents=True,exist_ok=True)
        fresh_ck=dict(ck)
        fresh_ck['model_state_dict']=best_state
        fresh_ck['65Y_finetune']={'source_checkpoint_sha256':sha(checkpoint_file),
            'source_checkpoint':str(checkpoint_file),'segment':seg,'member':m,
            'trained_heads':['strain_operator','stress_operator'],
            'frozen_heads':['displacement_operator','force_coefficient_head'],
            'train_split_only':True,'validation_selected_epoch':best_epoch,
            'validation_baseline_loss':baseline_val,'validation_selected_loss':best_val,
            'constitutive_loss_used':False,'kinematic_loss_used':False,
            'weights_S_and_LE':FIELD_WEIGHTS.tolist(),'learning_rate':args.lr,'epochs_requested':args.epochs}
        torch.save(fresh_ck,member_dir/'best_v4_7region.pt')
        pd.DataFrame(history).to_csv(member_dir/'training_history.csv',index=False)
        row={'segment':seg,'member':m,'baseline_val_loss':baseline_val,'best_val_loss':best_val,
             'improvement_pct':100*(baseline_val-best_val)/max(baseline_val,1e-12),
             'selected_epoch':best_epoch,'displacement_and_force_unchanged':True}
        results.append(row)
        print('  selected epoch',best_epoch,'val improvement %.3f%%'%row['improvement_pct'],flush=True)
    pd.DataFrame(results).to_csv(out/'65Y_B_validation_training_summary.csv',index=False)
    (out/'65Y_B_manifest.json').write_text(json.dumps({'step':'65Y-B','source':'original 64N trained checkpoints',
      'material_case':'original local V4 training cases (not middle 65W target)',
      'train_and_val_only':True,'test_split_unused':True,'members':len(plans),
      'weighting':FIELD_WEIGHTS.tolist(),'frozen_displacement_and_force_heads':True,
      'no_new_kinematic_or_constitutive_penalty':True,
      'warning':'Checkpoints are CANDIDATES. Do NOT overwrite results/v4_7region_direct or deploy in 65V coupling.'},indent=2))
    print('65Y-B COMPLETE:',out)

if __name__=='__main__':main()
