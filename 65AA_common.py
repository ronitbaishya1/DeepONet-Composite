def source_checkpoint(root, segment, member):
    return (root / 'results' / '65Z_nonlinear_mechanics' / 'B_constitutive' /
            segment / ('member_%02d' % member) / 'best_v4_7region.pt')


def load_data(root, segment):
    ds = co.segment_data(root, segment)
    folder = root / 'data' / 'hybrid_bulk_7region' / segment
    files = [folder / ('U%d.npy' % i) for i in (1,2,3)]
    for file in files:
        if not file.is_file():
            raise FileNotFoundError('Missing 64J displacement array: '+str(file))
    U = np.stack([np.load(p, allow_pickle=False) for p in files], axis=-1).astype(np.float32)
    if U.shape != (len(ds['branch_inputs']), len(ds['coordinates']), 3):
        raise RuntimeError('Incorrect U1/U2/U3 target dimensions: '+str(U.shape))
    if not np.all(np.isfinite(U)):
        raise RuntimeError('Nonfinite FEM training displacement')
    ds['U'] = U
    return ds


def element_dN_numpy(ds):
    # C3D8R B was generated by 64J from original element coordinates.
    B = np.asarray(ds['B_center'], dtype=np.float64)
    dN = np.stack((B[:,0,0::3], B[:,1,1::3], B[:,2,2::3]), axis=-1)
    if dN.shape != (len(ds['element_node_indices']), 8, 3):
        raise RuntimeError('Invalid C3D8R shape-function gradient matrix')
    # Check partition of unity; catches incorrect B indexing/order.
    if np.max(np.abs(dN.sum(axis=1))) > 2e-5:
        raise RuntimeError('Shape functions fail zero derivative sum. Do not proceed.')
    return dN.astype(np.float32)


def gradient_numpy(U, ds):
    U = np.asarray(U, dtype=np.float64)
    single = U.ndim == 2
    if single:
        U = U[None,:,:]
    dN = element_dN_numpy(ds).astype(np.float64)
    conn = np.asarray(ds['element_node_indices'], dtype=np.int64)
    gradients = np.einsum('beai,eaj->beij', U[:,conn,:], dN, optimize=True)
    return gradients[0] if single else gradients


def gradient_torch(U, connectivity, dN):
    # U [batch,nodes,3]; dN [elements,8,3] - differentiable on CPU/MPS.
    element_U = U[:,connectivity,:]
    return torch.einsum('beai,eaj->beij', element_U, dN)


def tensor_inputs(ck, ds, device):
    bn, nn, _ = co.scaled_inputs(ck, ds)
    branch = torch.as_tensor(np.array(bn, copy=True), dtype=torch.float32, device=device)
    nodes = torch.as_tensor(np.array(nn, copy=True), dtype=torch.float32, device=device)
    con = torch.as_tensor(np.array(ds['element_node_indices'],copy=True),dtype=torch.long,device=device)
    dn = torch.as_tensor(np.array(element_dN_numpy(ds),copy=True),dtype=torch.float32,device=device)
    umean = torch.as_tensor(np.array(ck['U_mean'],copy=True),dtype=torch.float32,device=device).reshape(1,1,3)
    ustd = torch.as_tensor(np.array(ck['U_std'],copy=True),dtype=torch.float32,device=device).reshape(1,1,3)
    bmean = torch.as_tensor(np.array(ck['branch_mean'],copy=True),dtype=torch.float32,device=device).reshape(1,-1)
    bstd = torch.as_tensor(np.array(ck['branch_std'],copy=True),dtype=torch.float32,device=device).reshape(1,-1)
    context = co.interface_context(ds.get('_root',None) or Path('.'),ds,device)
    return dict(branch=branch,nodes=nodes,connectivity=con,dN=dn,umean=umean,
                ustd=ustd,bmean=bmean,bstd=bstd,context=context)


def predict_torch(model, inputs, case_ids, correct=True):
    from src.hard_interface_compatibility_7region import apply_hard_compatibility_7region
    b = inputs['branch'][case_ids]
    raw = model.displacement_operator(b,inputs['nodes'])*inputs['ustd']+inputs['umean']
    if not correct:
        return raw
    corrected = apply_hard_compatibility_7region(
        raw_displacement=raw,
        branch_physical=b*inputs['bstd']+inputs['bmean'],
        context=inputs['context'])
    return corrected


def predict_numpy(model, inputs, indices, batch_size=4, correct=True):
    model.eval()
    output=[]
    with torch.no_grad():
        for start in range(0,len(indices),batch_size):
            ids=np.asarray(indices[start:start+batch_size],dtype=np.int64)
            out=predict_torch(model,inputs,ids,correct=correct)
            output.append(out.detach().cpu().numpy())
    return np.concatenate(output,axis=0)


def errors(U_pred,U_ref,ds,LE_ref=None):
    grad_pred=gradient_numpy(U_pred,ds)
    grad_ref=gradient_numpy(U_ref,ds)
    d={
       'U_vector_rel_l2_pct':co.relative_l2(U_pred,U_ref),
       'U2_rel_l2_pct':co.relative_l2(U_pred[...,1],U_ref[...,1]),
       'U2_rmse_mm':float(np.sqrt(np.mean((U_pred[...,1]-U_ref[...,1])**2))),
       'gradient_rel_l2_pct':co.relative_l2(grad_pred,grad_ref),
       'gradient_rmse':float(np.sqrt(np.mean((grad_pred-grad_ref)**2))),
    }
    if LE_ref is not None:
        cols={'LE11':0,'LE22':1,'LE12':3}
        log_pred=np.stack([co.log_material_strain_eng(u,ds['element_node_indices'],ds['B_center'])
                           for u in U_pred])
        for name,k in cols.items():
            d['logU_'+name+'_rel_l2_pct']=co.relative_l2(log_pred[...,k],LE_ref[...,k])
        log_reference=np.stack([co.log_material_strain_eng(u,ds['element_node_indices'],ds['B_center'])
                           for u in U_ref])
        for name,k in cols.items():
            d['reference_logU_'+name+'_rel_l2_pct']=co.relative_l2(log_reference[...,k],LE_ref[...,k])
    return d


def frozen_heads_equal(left,right):
    a=left['model_state_dict'];b=right['model_state_dict']
    if a.keys()!=b.keys():return False
    return all(torch.equal(a[k],b[k]) for k in a if not k.startswith('displacement_operator.'))


def init_case(root,segment,member,device):
    if str(root) not in sys.path:sys.path.insert(0,str(root))
    ds=load_data(root,segment)
    ds['_root']=root
    path=source_checkpoint(root,segment,member)
    ck=co.load_checkpoint(path)
    if '65Z_physics_finetune' not in ck:
        raise RuntimeError('Expected Step65Z constitutive checkpoint: '+str(path))
    model=co.make_model(ck,device)
    inputs=tensor_inputs(ck,ds,device)
    return ds,ck,model,inputs,path
